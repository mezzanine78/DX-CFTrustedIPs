<#
install.ps1 - one-line installer for the DX CF-IP collector (DX Cloudflare trusted-IP updater).

Recommended (technician, elevated PowerShell; prompts for the token, nothing sensitive in history):
  $env:DX_CFIP_CLIENTCODE='ACME'; $env:DX_CFIP_ENDPOINT='https://cfip.example.com.au'; irm https://raw.githubusercontent.com/mezzanine78/DX-CFTrustedIPs/main/install.ps1 | iex
RMM / SYSTEM (token from a secure RMM variable, never typed into an interactive console):
  $env:DX_CFIP_CLIENTCODE='ACME'; $env:DX_CFIP_ENDPOINT='https://cfip.example.com.au'; $env:DX_CFIP_TOKEN='<secure var>'; irm <url>/install.ps1 | iex
Uninstall:
  $env:DX_CFIP_UNINSTALL='1'; irm <url>/install.ps1 | iex

Inputs (environment variables; there is no param() block so it works through iex):
  DX_CFIP_CLIENTCODE     client code registered on the central service (required)
  DX_CFIP_ENDPOINT       https://host or https://host/report of the central service (required; DX_CFIP_REPORTURL also accepted)
  DX_CFIP_TOKEN          report token; if empty and the session is interactive you are prompted (hidden input).
                         Cleared from the environment when the installer finishes.
  DX_CFIP_HEARTBEATHOURS heartbeat interval, default 6
  DX_CFIP_UNINSTALL=1    remove task, collector, config and state (logs in C:\DX\Logs are kept)
  DX_CFIP_NORUNNOW=1     do not run the collector once after installing
  DX_CFIP_ROOTDIR        default C:\DX
  DX_CFIP_REPOURL        raw base URL, default https://raw.githubusercontent.com/mezzanine78/DX-CFTrustedIPs/main
                         (point it at a commit, .../<sha>, for an immutable release; the pins below must match it)

Elevation: it does NOT self-elevate. Start-Process -Verb RunAs loses the caller's env vars and the iex context,
and handing the token to the elevated process means a command line (visible in process listings / 4688 events)
or a temp file. Not elevated -> exits 2 with instructions to open an elevated PowerShell and re-run.

Downloads collector/DXCfip.Install.ps1 (shared install logic) and collector/Invoke-DXCfipCollector.ps1 over
TLS 1.2 (1.3 on build 20348+), checks each against the SHA256 pinned below (set by tools/Update-Pins.ps1 per
release) and that it parses, then installs exactly like the N-central installer.

Exit codes / $LASTEXITCODE:
  0 = installed (first run OK) / uninstalled
  1 = bad or missing input, not Windows, install error
  2 = not elevated
  3 = download failed, hash mismatch or downloaded script does not parse
  4 = installed, but the first collector run failed (task stays registered)
Never calls exit in an interactive console (sets $global:LASTEXITCODE instead). No secrets in this file.
#>
& {
    $ErrorActionPreference = 'Stop'
    $ProgressPreference = 'SilentlyContinue'
    $DefaultRepoUrl = 'https://raw.githubusercontent.com/mezzanine78/DX-CFTrustedIPs/main'
    # BEGIN-PINS (generated by tools/Update-Pins.ps1 - SHA256 of the files at this release)
    $Pins = @{
        'collector/DXCfip.Install.ps1'         = '6DB3B379E113F65B5683369908DA0CCFA4948BF373DC74108834DA363CC5445E'
        'collector/Invoke-DXCfipCollector.ps1' = '386134AD069CE6BEB1DDBF745A801D8B8896890C6EBABBD5378468D969635A5C'
    }
    # END-PINS

    function Write-DXLine([string]$Msg, [string]$Level = 'INFO') {
        Write-Host ('{0} DX cfip-install {1,-5} {2}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $Msg)
    }

    function Exit-DXInstaller([int]$Code, [string]$Msg) {
        $lvl = 'INFO'
        if ($Code -ne 0) { $lvl = 'ERROR' }
        Write-DXLine "$Msg (exit $Code)" $lvl
        $global:LASTEXITCODE = $Code
        # Only end the process when nobody is sitting at it (RMM, SYSTEM, -Command / -File / -NonInteractive).
        if (-not [Environment]::UserInteractive -or
            ([Environment]::GetCommandLineArgs() -match '^-(c|command|noni|noninteractive|file|f|encodedcommand|e|ec)$')) {
            exit $Code
        }
    }

    function Get-DXEnv([string]$Name) {
        $v = [Environment]::GetEnvironmentVariable($Name)
        if ($null -eq $v) { return '' }
        return $v.Trim()
    }

    function Get-DXRemoteScript([string]$BaseUrl, [string]$RelPath, [string]$Marker) {
        $tmp = [IO.Path]::GetTempFileName()
        try {
            Invoke-WebRequest -Uri "$BaseUrl/$RelPath" -UseBasicParsing -TimeoutSec 60 -OutFile $tmp
            $hash = (Get-FileHash -LiteralPath $tmp -Algorithm SHA256).Hash
            $pin = [string]$Pins[$RelPath]
            if ($pin) {
                if ($hash -ne $pin.ToUpperInvariant()) { throw "SHA256 mismatch for $RelPath (got $hash, pinned $pin)" }
                Write-DXLine "$RelPath SHA256 OK"
            }
            else { Write-DXLine "$RelPath has no pinned SHA256 (dev build): parse check only, SHA256 $hash" 'WARN' }
            $text = [IO.File]::ReadAllText($tmp, [Text.Encoding]::UTF8)
            $tokens = $null; $errors = $null
            [void][Management.Automation.Language.Parser]::ParseInput($text, [ref]$tokens, [ref]$errors)
            if (@($errors).Count) { throw "$RelPath does not parse: $($errors[0].Message)" }
            if (-not $text.Contains($Marker)) { throw "$RelPath is not the expected file" }
            return $text
        }
        finally { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
    }

    $rc = 1
    $msg = 'failed'
    $token = $null
    try {
        # TLS 1.2 (+1.3 where the OS has it) before the first download
        try {
            $proto = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
            if ($env:OS -eq 'Windows_NT' -and [Environment]::OSVersion.Version.Build -ge 20348 -and
                [enum]::GetNames([Net.SecurityProtocolType]) -contains 'Tls13') { $proto = $proto -bor [Net.SecurityProtocolType]::Tls13 }
            [Net.ServicePointManager]::SecurityProtocol = $proto
        }
        catch { $null = $_ }

        $repo = Get-DXEnv 'DX_CFIP_REPOURL'
        if (-not $repo) { $repo = $DefaultRepoUrl }
        $repo = $repo.TrimEnd('/')
        if ($repo -notmatch '^https://[^\s/]+/' -and $repo -notmatch '^http://(127\.0\.0\.1|localhost)(:\d+)?(/|$)') {
            $msg = 'DX_CFIP_REPOURL must be an https:// URL'; throw [InvalidOperationException]'input'
        }
        $rootDir = Get-DXEnv 'DX_CFIP_ROOTDIR'
        if (-not $rootDir) { $rootDir = 'C:\DX' }
        $uninstall = (Get-DXEnv 'DX_CFIP_UNINSTALL') -match '^(1|true|yes|on)$'

        try { $lib = Get-DXRemoteScript -BaseUrl $repo -RelPath 'collector/DXCfip.Install.ps1' -Marker 'function Invoke-DXCfipInstall' }
        catch { $rc = 3; $msg = "could not get the shared install code: $($_.Exception.Message)"; throw }
        . ([scriptblock]::Create($lib))

        if (-not (& $DXCfipOps.IsWindows)) { $rc = 1; $msg = 'Windows only'; throw [InvalidOperationException]'input' }
        if (-not (& $DXCfipOps.IsElevated)) {
            Write-DXLine 'This needs an elevated PowerShell (Administrator) or SYSTEM.' 'ERROR'
            Write-DXLine 'Start > type PowerShell > right-click > Run as administrator, then run the one-liner again.' 'ERROR'
            Write-DXLine 'Not self-elevating on purpose: the elevated window would not get your env vars, and passing the token to it would expose it on a command line.' 'ERROR'
            $rc = 2; $msg = 'not elevated'; throw [InvalidOperationException]'input'
        }

        if ($uninstall) {
            $rc = Invoke-DXCfipUninstall -RootDir $rootDir
            $msg = 'uninstall finished'
        }
        else {
            $code = (Get-DXEnv 'DX_CFIP_CLIENTCODE').ToUpperInvariant()
            $endpoint = Get-DXEnv 'DX_CFIP_ENDPOINT'
            if (-not $endpoint) { $endpoint = Get-DXEnv 'DX_CFIP_REPORTURL' }
            $reportUrl = ConvertTo-DXReportUrl $endpoint
            $hb = 6
            $hbRaw = Get-DXEnv 'DX_CFIP_HEARTBEATHOURS'
            if ($hbRaw -and (-not [int]::TryParse($hbRaw, [ref]$hb) -or $hb -lt 1)) { $rc = 1; $msg = 'DX_CFIP_HEARTBEATHOURS must be a whole number >= 1'; throw [InvalidOperationException]'input' }
            if ($code -notmatch '^[A-Z0-9][A-Z0-9_-]{1,31}$') { $rc = 1; $msg = 'set $env:DX_CFIP_CLIENTCODE (2-32 chars: A-Z 0-9 _ -)'; throw [InvalidOperationException]'input' }
            if (-not $reportUrl) { $rc = 1; $msg = 'set $env:DX_CFIP_ENDPOINT to https://<cfip host>'; throw [InvalidOperationException]'input' }

            $token = Get-DXEnv 'DX_CFIP_TOKEN'
            if (-not $token) {
                if (-not (& $DXCfipOps.CanPrompt)) { $rc = 1; $msg = 'DX_CFIP_TOKEN is empty and this session cannot prompt (set it from a secure RMM variable)'; throw [InvalidOperationException]'input' }
                $secure = & $DXCfipOps.ReadToken
                if ($secure -is [Security.SecureString] -and $secure.Length -gt 0) {
                    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
                    try { $token = ([Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)).Trim() }
                    finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr); $secure.Dispose(); $secure = $null }
                }
                if (-not $token) { $rc = 1; $msg = 'no token entered'; throw [InvalidOperationException]'input' }
            }

            try { $collector = Get-DXRemoteScript -BaseUrl $repo -RelPath 'collector/Invoke-DXCfipCollector.ps1' -Marker $DXCfipMarker }
            catch { $rc = 3; $msg = "could not get the collector: $($_.Exception.Message)"; throw }

            $rc = Invoke-DXCfipInstall -ClientCode $code -ReportUrl $reportUrl -Token $token -HeartbeatHours $hb `
                -CollectorContent $collector -RootDir $rootDir -NoRunNow:((Get-DXEnv 'DX_CFIP_NORUNNOW') -match '^(1|true|yes|on)$')
            $msg = 'install finished'
        }
    }
    catch {
        if ($_.Exception.Message -ne 'input' -and $msg -eq 'failed') { $msg = "unexpected error: $($_.Exception.Message)" }
    }
    finally {
        # The token is never logged; drop every copy we hold, and the env var, whatever happened.
        $token = $null
        Remove-Item Env:DX_CFIP_TOKEN -ErrorAction SilentlyContinue
    }
    Exit-DXInstaller $rc $msg
}
